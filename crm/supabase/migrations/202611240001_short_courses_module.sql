-- A tightly scoped RPC is used by the public form, so anonymous users cannot set
-- internal assignment, follow-up, registration, or attendance fields.
create or replace function public.submit_short_course_application(
  p_course_id uuid,
  p_first_name text,
  p_last_name text,
  p_phone text,
  p_email text default null,
  p_date_of_birth date default null,
  p_gender text default null,
  p_nationality text default null,
  p_highest_qualification text default null,
  p_qualification_details text default null,
  p_source text default 'Website',
  p_expected_outcome text default null
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  if nullif(trim(p_first_name), '') is null or nullif(trim(p_last_name), '') is null
    or nullif(trim(p_phone), '') is null then
    raise exception 'First name, last name and phone number are required';
  end if;

  if not exists (
    select 1 from public.short_courses c
    where c.id = p_course_id and c.status = 'active' and c.public_visible = true
      and (c.application_deadline is null or c.application_deadline >= current_date)
  ) then
    raise exception 'This short course is not currently accepting applications';
  end if;

  insert into public.short_course_applications (
    course_id, first_name, last_name, phone, email, date_of_birth, gender,
    nationality, highest_qualification, qualification_details, source, expected_outcome
  ) values (
    p_course_id, trim(p_first_name), trim(p_last_name), trim(p_phone), nullif(trim(p_email), ''),
    p_date_of_birth, nullif(trim(p_gender), ''), nullif(trim(p_nationality), ''),
    nullif(trim(p_highest_qualification), ''), nullif(trim(p_qualification_details), ''),
    coalesce(nullif(trim(p_source), ''), 'Website'), nullif(trim(p_expected_outcome), '')
  ) returning id into v_id;

  return v_id;
end;
$$;

revoke all on function public.submit_short_course_application(uuid,text,text,text,text,date,text,text,text,text,text,text) from public;
grant execute on function public.submit_short_course_application(uuid,text,text,text,text,date,text,text,text,text,text,text) to anon, authenticated;
