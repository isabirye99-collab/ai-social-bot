-- CIU Short Courses module: course catalogue, public applications, coordinator activity and attendance.
create table if not exists public.short_courses (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  course_code text,
  description text,
  category text,
  duration text,
  delivery_mode text not null default 'In person' check (delivery_mode in ('In person','Online','Hybrid')),
  venue text,
  fee_amount numeric(12,2),
  currency text not null default 'UGX',
  start_date date,
  end_date date,
  application_deadline date,
  status text not null default 'active' check (status in ('draft','active','closed','completed')),
  public_visible boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  updated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.short_course_applications (
  id uuid primary key default gen_random_uuid(),
  application_number bigint generated by default as identity unique,
  course_id uuid not null references public.short_courses(id) on delete restrict,
  first_name text not null,
  last_name text not null,
  phone text not null,
  email text,
  date_of_birth date,
  gender text,
  nationality text,
  highest_qualification text,
  qualification_details text,
  source text,
  expected_outcome text,
  application_status text not null default 'new' check (application_status in ('new','contacted','qualified','registered','waitlisted','not_eligible','withdrawn','completed')),
  attendance_status text not null default 'not_started' check (attendance_status in ('not_started','attending','irregular','not_attending','completed','withdrawn')),
  assigned_to uuid references public.profiles(id) on delete set null,
  last_contacted_at timestamptz,
  last_feedback text,
  next_follow_up_at timestamptz,
  registration_date date,
  first_class_date date,
  source_sheet text,
  legacy_reference text,
  submitted_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.short_course_activities (
  id uuid primary key default gen_random_uuid(),
  application_id uuid not null references public.short_course_applications(id) on delete cascade,
  activity_type text not null default 'call' check (activity_type in ('call','whatsapp','email','meeting','feedback','status_change','other')),
  outcome text,
  notes text,
  next_follow_up_at timestamptz,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.short_course_attendance (
  id uuid primary key default gen_random_uuid(),
  application_id uuid not null references public.short_course_applications(id) on delete cascade,
  session_date date not null default current_date,
  attendance_status text not null check (attendance_status in ('present','absent','late','excused')),
  notes text,
  recorded_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (application_id, session_date)
);

create index if not exists short_course_applications_course_idx on public.short_course_applications(course_id);
create index if not exists short_course_applications_assigned_idx on public.short_course_applications(assigned_to);
create index if not exists short_course_applications_status_idx on public.short_course_applications(application_status, attendance_status);
create index if not exists short_course_activities_application_idx on public.short_course_activities(application_id, created_at desc);
create index if not exists short_course_attendance_application_idx on public.short_course_attendance(application_id, session_date desc);

alter table public.short_courses enable row level security;
alter table public.short_course_applications enable row level security;
alter table public.short_course_activities enable row level security;
alter table public.short_course_attendance enable row level security;

